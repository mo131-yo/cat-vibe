/**
 * ImageResponse-ийн анхны фонт кирилл үсэг агуулаагүй тул Noto Sans-ыг
 * гараар ачаална — үгүй бол монгол текст хоосон дөрвөлжин болно.
 */
async function loadFonts() {
  const [bold, regular] = await Promise.all([
    readFile(join(FONT_DIR, "NotoSans-Bold.ttf")),
    readFile(join(FONT_DIR, "NotoSans-Regular.ttf")),
  ]);
  return [
    { name: "Noto Sans", data: bold, weight: 700 as const, style: "normal" as const },
    {
      name: "Noto Sans",
      data: regular,
      weight: 400 as const,
      style: "normal" as const,
    },
  ];
}

