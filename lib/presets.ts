/**
 * Хүлээн авагчийн хуудсанд preset id хадгалагддаггүй (зөвхөн текст ирнэ).
 * Тиймээс асуултын текстээр нь буцааж таньж, тохирсон шоолол/сонголтыг өгнө.
 * Олдохгүй бол `custom` — өөрөө бичсэн асуулт гэсэн үг.
 */
export function presetByQuestion(question: string): Preset {
  return (
    PRESETS.find((p) => p.question && p.question === question) ??
    PRESETS[PRESETS.length - 1]
  );
}
